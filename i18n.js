function tr(key) {
  var lang = (typeof state !== "undefined" && state.lang) ? state.lang : "fr";
  var dict = I18N[lang] || I18N.fr;
  return (key in dict) ? dict[key] : (I18N.fr[key] || key);
}

function getStoredLang() {
  try { return localStorage.getItem("ecoroute_lang") || "fr"; } catch (e) { return "fr"; }
}
function setLang(lang) {
  state.lang = lang;
  try { localStorage.setItem("ecoroute_lang", lang); } catch (e) {}
  document.documentElement.setAttribute("lang", lang);
  document.documentElement.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");
  render();
}
